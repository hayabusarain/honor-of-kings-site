/**
 * サイト内検索の文字列正規化。
 *
 * 検索が効かない原因はほぼ表記の揺れで、内訳は4つある。
 *   1. 全角と半角  … 「ＣＳ」と「CS」、「１２３」と「123」
 *   2. 区切り      … 「タイラント (Tyrant)」の空白、「赤バフ・青バフ」の中黒
 *   3. 大文字小文字 … 「Hok」と「HoK」
 *   4. カタカナとひらがな … 別名データはひらがなで持っているが、読者はカタカナで打つ
 *
 * ヒーロー一覧が持っていたインラインの実装をここへ出し、
 * 横断検索（GlobalSearchModal）とパッチ表からも同じ関数を使う。
 * 片方だけ正規化すると「一覧では出るのに検索では出ない」がまた起きる。
 *
 * カタカナの範囲は [ァ-ヶ] にする。[ァ-ヺ] にすると「ヺ」が結合済みの
 * ひらがなに対応せず、-0x60 の引き算で別の文字に化ける。
 */
export function searchNormalize(input: string): string {
  return (input || '')
    // 全角英数と半角カナを畳む。NFKC は「㌦」のような合字も開く
    .normalize('NFKC')
    // 空白・全角空白・中黒を落とす。「タイラント (Tyrant)」を「たいらんと(tyrant)」にする
    .replace(/[\s　・]+/g, '')
    .toLowerCase()
    // カタカナ→ひらがな。別名データがひらがななので、そちらへ寄せる
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
}
