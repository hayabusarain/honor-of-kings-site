/**
 * Amazon アソシエイトの紹介枠の設定。**サイト内で1箇所だけ、全ページの本文最上部に出る。**
 *
 * ■ 出す・出さないの切り替え
 *
 * `tag` か `url` か `title.ja` が空なら、コンポーネントは null を返して**何も描画しない**。
 * つまりこのファイルを空のままデプロイしても画面には出ない。出したくなったら埋める。
 *
 * **9/14 の AdSense 再審査までは空のままにしておくことを勧める。**
 * 不承認の理由は「有用性の低いコンテンツ」で、この判定は広告とコンテンツの比率も見る。
 * 全ページの本文最上部に広告を足すのは、審査の直前にやることではない。
 * 経緯は hub-game-portal/docs/ADSENSE_REVIEW_LOG.md にある。
 *
 * ■ Amazon 側の必須要件（守らないと規約違反）
 *
 * 1. **必須表記。** 運営規約は「Amazonのアソシエイトとして、［名称］は適格販売により
 *    収入を得ています。」を目立つように掲示することを義務づけている。
 *    コンポーネントがリンクの隣に必ず出す。消さないこと。
 *    プライバシーポリシーにも同じ趣旨の節を置いてある。
 *
 * 2. **180日ルール。** 申請から180日以内に3件の適格販売が無いとアカウントが閉鎖される。
 *    https://affiliate.amazon.co.jp/help/node/topic/G7MJTPEP9NC3YKMG
 *
 * ■ 商品の選び方
 *
 * 読者はモバイル MOBA を遊ぶ人で、日本からの訪問がほとんど。
 * ガイドの設定節に「指追従（手動エイム）を推奨」「端末が発熱して動作が重くなる」と
 * 書いてあり、指サックやスマホ用冷却クーラーはその文脈と矛盾しない。
 * **サイトの記述と食い違う商品を置かないこと。** 書いていないことを勧める形になる。
 */
type AmazonAssociateConfig = {
  tag: string;
  url: string;
  title: { ja: string; en: string };
  note: { ja: string; en: string };
};

export const AMAZON_ASSOCIATE: AmazonAssociateConfig = {
  /** アソシエイトのトラッキングID（例: xxxxxx-22）。空なら何も出ない */
  tag: '',

  /** 商品ページのURL。tag は自動で付くので、URLには付けないこと */
  url: '',

  /** リンクの文言。商品名そのままより、何のためのものか分かる短い語がよい */
  title: {
    ja: '',
    en: '',
  },

  /** リンクの前に置く一文。なぜこのサイトがこれを出すのかが分かるように */
  note: {
    ja: '',
    en: '',
  },
};
